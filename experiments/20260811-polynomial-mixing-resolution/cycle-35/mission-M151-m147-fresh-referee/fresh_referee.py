def record(x: Q) -> dict[str, str]:
    return {"numerator": str(x.numerator), "denominator": str(x.denominator)}


@functools.lru_cache(None)
def weight(n: int) -> Q:
    if n < 1:
        raise ValueError(n)
    return Q(n ** (n - 1), math.factorial(n))


@functools.lru_cache(None)
def compositions(n: int) -> tuple[tuple[int, ...], ...]:
    """Ordered positive compositions, generated by subsets of cut sites."""
    if n == 0:
        return ((),)
    rows: list[tuple[int, ...]] = []
    for mask in range(1 << (n - 1)):
        start = 0
        parts: list[int] = []
        for site in range(n - 1):
            if mask & (1 << site):
                parts.append(site + 1 - start)
                start = site + 1
        parts.append(n - start)
        rows.append(tuple(parts))
    return tuple(rows)


def rising(x: int, r: int) -> int:
    ans = 1
    for i in range(r):
        ans *= x + i
    return ans


def falling(x: int, r: int) -> int:
    ans = 1
    for i in range(r):
        ans *= x - i
    return ans


def forest_closed(n: int, p: int) -> Q:
    if (n, p) == (0, 0):
        return Q(1)
    if not (1 <= p <= n):
        return Q(0)
    return Q(p * n ** (n - p), n * math.factorial(n - p))


def forest_enumerated(n: int, p: int) -> Q:
    return sum(
        (math.prod(weight(a) for a in alpha) for alpha in compositions(n) if len(alpha) == p),
        Q(0),
    )


def composition_mass(alpha: tuple[int, ...]) -> Q:
    s = sum(alpha)
    return Q(math.prod(weight(a) for a in alpha), math.factorial(len(alpha)) * weight(s + 1))


def split_q(s: int, bottom: int) -> Q:
    return weight(s + 1 - bottom) * weight(bottom) / weight(s + 1)


def attachment_original(K: int, R: int, degree: int, j: int) -> Q:
    return Q(
        math.comb(R + j, j) * math.comb(K - R - 1 + degree - j, degree - j),
        math.comb(K + degree, degree),
    )


def attachment_transformed(kappa: int, deficit: int, degree: int, j: int) -> Q:
    return Q(
        math.comb(degree, j)
        * rising(deficit, degree - j)
        * rising(kappa - deficit, j),
        rising(kappa, degree),
    )


def contextual_mean(alpha: tuple[int, ...], kappa: int, deficit: int, bottom: int) -> Q:
    degree = len(alpha)
    last = alpha[-1]
    if last < bottom:
        return Q(0)
    if last == bottom:
        return Q(degree * rising(deficit, degree - 1), rising(kappa, degree - 1))
    return split_q(last - 1, bottom) * (
        1 - Q(rising(deficit, degree), rising(kappa, degree))
    )


@functools.lru_cache(None)
def canonical_endpoints(s: int) -> tuple[tuple[int, ...], ...]:
    endpoints: set[tuple[int, ...]] = set()
    for source in compositions(s):
        for cut in range(1, len(source)):
            endpoint = (sum(source[:cut]),) + source[cut:]
            if endpoint[0] + endpoint[1] - 1 >= 2:
                endpoints.add(endpoint)
    return tuple(sorted(endpoints, key=lambda row: (len(row), row)))


def refines_endpoint(source: tuple[int, ...], endpoint: tuple[int, ...]) -> bool:
    for cut in range(1, len(source)):
        if sum(source[:cut]) == endpoint[0] and source[cut:] == endpoint[1:]:
            return True
    return False


@functools.lru_cache(None)
def reset_energy(s: int, K: int, R: int, bottom: int) -> Q:
    kappa = K + 1
    deficit = K - R
    q = split_q(s, bottom)
    answer = Q(0)
    for endpoint in canonical_endpoints(s):
        current = sum(
            (
                composition_mass(source)
                * (contextual_mean(source, kappa, deficit, bottom) - q)
                for source in compositions(s)
                if refines_endpoint(source, endpoint)
            ),
            Q(0),
        )
        capacity = len(endpoint) * composition_mass(endpoint)
        answer += current * current / capacity
    return answer


@functools.lru_cache(None)
def direct_excursion(s: int, K: int, R: int, bottom: int) -> Q:
    answer = reset_energy(s, K, R, bottom)
    for root in compositions(s):
        degree = len(root)
        last = root[-1]
        if last <= bottom or last - 1 < 2:
            continue
        mass = composition_mass(root)
        for j in range(1, degree + 1):
            answer += (
                mass
                * attachment_original(K, R, degree, j)
                * direct_excursion(last - 1, K + degree, R + j, bottom)
            )
    return answer


def grouped_normalized_rhs(s: int, K: int, R: int, bottom: int) -> Q:
    excess = s - bottom
    kappa = K + 1
    deficit = K - R
    parent_q = split_q(s, bottom)
    answer = reset_energy(s, K, R, bottom) / parent_q
    for h in range(1, excess + 1):
        child_s = bottom + h - 1
        if child_s < 2:
            continue
        prefix_sum = excess - h
        for degree in range(1, prefix_sum + 2):
            prefix_mass = forest_closed(prefix_sum, degree - 1)
            ratio = weight(bottom) / weight(bottom + h)
            normalized_group_mass = prefix_mass / (
                math.factorial(degree) * weight(excess + 1) * ratio
            )
            child_q = split_q(child_s, bottom)
            for j in range(1, degree + 1):
                nu = attachment_transformed(kappa, deficit, degree, j)
                child_K = K + degree
                child_R = R + j
                answer += (
                    normalized_group_mass
                    * nu
                    * child_q
                    * direct_excursion(child_s, child_K, child_R, bottom)
                    / child_q
                )
    return answer


def lambda_value(first: int, degree: int) -> Q:
    return math.factorial(degree - 1) * sum(
        (
            Q(p * falling(first, p), math.factorial(p + degree - 1) * first**p)
            for p in range(1, first + 1)
        ),
        Q(0),
    )


def scalar_c(s: int) -> Q:
    return sum(
        (
            weight(first)
            * forest_closed(s - first, degree - 1)
            / (math.factorial(degree - 1) * weight(s + 1))
            * lambda_value(first, degree) ** 2
            for degree in range(2, s + 1)
            for first in range(1, s - degree + 2)
        ),
        Q(0),
    )


def l1_closed(K: int, R: int) -> Q:
    p = Q(K - R, K + 1)
    return Q(1, 16) + (2 * p - Q(3, 8)) ** 2 / 4


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    failures: list[dict[str, object]] = []

    experiment_root = Path(__file__).resolve().parents[2]
    frozen = experiment_root / "cycle-34" / "mission-M147-all-suffix-scalar-envelope"
    observed_hashes = {}
    for name, expected in EXPECTED_HASHES.items():
        observed = hashlib.sha256((frozen / name).read_bytes()).hexdigest()
        observed_hashes[name] = observed
        if observed != expected:
            failures.append({"kind": "immutable-hash", "file": name, "observed": observed})

    forest_rows = 0
    for n in range(0, 10):
        for p in range(0, n + 1):
            forest_rows += 1
            if forest_enumerated(n, p) != forest_closed(n, p):
                failures.append({"kind": "forest-coefficient", "n": n, "p": p})

    attachment_rows = 0
    for K, R in [(1, 0)] + [(K, R) for K in range(2, 13) for R in range(1, K)]:
        kappa, deficit = K + 1, K - R
        for degree in range(1, 10):
            row = []
            for j in range(degree + 1):
                a = attachment_original(K, R, degree, j)
                b = attachment_transformed(kappa, deficit, degree, j)
                attachment_rows += 1
                if a != b:
                    failures.append({"kind": "attachment-transform", "state": [K, R, degree, j]})
                row.append(a)
            if sum(row, Q(0)) != 1:
                failures.append({"kind": "attachment-normalization", "state": [K, R, degree]})
            mean_added_deficit = sum(
                ((degree - j) * row[j] for j in range(degree + 1)), Q(0)
            )
            if mean_added_deficit != Q(degree * deficit, kappa):
                failures.append({"kind": "beta-binomial-mean", "state": [K, R, degree]})
            if Q(deficit + mean_added_deficit, kappa + degree) != Q(deficit, kappa):
                failures.append({"kind": "deficit-ratio-martingale", "state": [K, R, degree]})
            for j in range(1, degree + 1):
                child_kappa = K + degree + 1
                child_deficit = K + degree - (R + j)
                if (child_kappa, child_deficit) != (kappa + degree, deficit + degree - j):
                    failures.append({"kind": "child-transform", "state": [K, R, degree, j]})

    root_rows = 0
    root_cases = 0
    for bottom in range(1, 6):
        for excess in range(0, 8):
            if bottom + excess < 2:
                continue
            for kappa, deficit in ((2, 1), (3, 1), (9, 1), (9, 4), (9, 7)):
                normalized_mean = Q(0)
                support = 0
                q = weight(excess + 1) * weight(bottom) / weight(bottom + excess + 1)
                for h in range(excess + 1):
                    for prefix in compositions(excess - h):
                        root = prefix + (bottom + h,)
                        degree = len(root)
                        literal = composition_mass(root) / q
                        ratio = weight(bottom) / weight(bottom + h)
                        formula = Q(
                            math.prod(weight(a) for a in prefix),
                            math.factorial(degree) * weight(excess + 1) * ratio,
                        )
                        root_rows += 1
                        support += 1
                        if literal != formula:
                            failures.append({"kind": "root-literal", "state": [bottom, excess, kappa, deficit, h, degree]})
                        normalized_mean += formula * contextual_mean(root, kappa, deficit, bottom)
                    for degree in range(1, excess - h + 2):
                        grouped = sum(
                            (
                                composition_mass(prefix + (bottom + h,)) / q
                                for prefix in compositions(excess - h)
                                if len(prefix) + 1 == degree
                            ),
                            Q(0),
                        )
                        group_formula = forest_closed(excess - h, degree - 1) / (
                            math.factorial(degree)
                            * weight(excess + 1)
                            * (weight(bottom) / weight(bottom + h))
                        )
                        if grouped != group_formula:
                            failures.append({"kind": "root-group", "state": [bottom, excess, h, degree]})
                if support != 2**excess:
                    failures.append({"kind": "root-support", "state": [bottom, excess], "count": support})
                if normalized_mean != 1:
                    failures.append({"kind": "root-mean", "state": [bottom, excess, kappa, deficit]})
                root_cases += 1

    recurrence_cases = []
    for bottom, excess, K, R in (
        (1, 1, 1, 0),
        (1, 2, 2, 1),
        (1, 4, 6, 2),
        (2, 1, 32, 1),
        (2, 1, 32, 31),
        (2, 3, 5, 1),
        (2, 5, 8, 7),
        (3, 4, 10, 4),
    ):
        s = bottom + excess
        lhs = direct_excursion(s, K, R, bottom) / split_q(s, bottom)
        rhs = grouped_normalized_rhs(s, K, R, bottom)
        recurrence_cases.append({"state_s_K_R_B": [s, K, R, bottom], "value": record(lhs)})
        if lhs != rhs:
            failures.append({"kind": "grouped-recurrence", "state": [s, K, R, bottom]})

    l1_rows = 0
    for K in range(1, 129):
        admissible_R = (0,) if K == 1 else range(1, K)
        for R in admissible_R:
            actual = direct_excursion(3, K, R, 2) / Q(3, 8)
            if actual != l1_closed(K, R):
                failures.append({"kind": "l1-formula", "state": [K, R]})
            l1_rows += 1

    budget = Q(5, 8)
    threshold = []
    for K in range(2, 81):
        margin = l1_closed(K, 1) - budget
        expected_sign = 0 if K == 31 else (1 if K >= 32 else -1)
        actual_sign = (margin > 0) - (margin < 0)
        if actual_sign != expected_sign:
            failures.append({"kind": "threshold", "K": K, "margin": str(margin)})
        threshold.append(actual_sign)
        if not l1_closed(K, K - 1) < budget:
            failures.append({"kind": "right-heavy-budget", "K": K})

    bad_F = l1_closed(32, 1)
    good_F = l1_closed(32, 31)
    bad_H = Q(3, 8) * bad_F
    good_H = Q(3, 8) * good_F
    expected_exact = {
        "bad_F": Q(175033, 278784),
        "good_F": Q(24313, 278784),
        "bad_H": Q(175033, 743424),
        "good_H": Q(24313, 743424),
        "bad_margin_H": Q(793, 743424),
        "threshold_K31_F": Q(5, 8),
        "C3": Q(9, 32),
    }
    observed_exact = {
        "bad_F": bad_F,
        "good_F": good_F,
        "bad_H": bad_H,
        "good_H": good_H,
        "bad_margin_H": bad_H - Q(15, 64),
        "threshold_K31_F": l1_closed(31, 1),
        "C3": scalar_c(3),
    }
    for name, expected in expected_exact.items():
        if observed_exact[name] != expected:
            failures.append({"kind": "exact-witness", "name": name, "observed": str(observed_exact[name])})

    reachability = []
    for target_K in (32, 64, 257):
        degree = target_K - 1
        parent = (target_K + 2, 1, 0, 2)
        root = (1,) * (target_K - 2) + (4,)
        if sum(root) != parent[0] or len(root) != degree or composition_mass(root) <= 0:
            failures.append({"kind": "reachable-root", "K": target_K})
        for j, expected_R in ((1, 1), (degree, target_K - 1)):
            probability = attachment_original(1, 0, degree, j)
            child = (3, 1 + degree, j, 2)
            if probability != Q(1, target_K) or child != (3, target_K, expected_R, 2):
                failures.append({"kind": "reachable-branch", "K": target_K, "j": j})
        reachability.append({"K": target_K, "root_degree": degree, "each_extreme_branch_probability": record(Q(1, target_K))})

    paired_named_data = {
        "L": 1,
        "B": 2,
        "s": 3,
        "q": record(split_q(3, 2)),
        "C_s": record(scalar_c(3)),
        "K": 32,
        "z": record(Q(1, 33)),
        "suffix_Cayley_ratios": [record(weight(n) / weight(n + 1)) for n in (2, 3)],
    }
    if bad_F == good_F:
        failures.append({"kind": "paired-values-not-distinct"})

    moment_rows = []
    for r in range(13):
        n = r + 1
        kappa = r + 4
        denominator = 2 ** (n - 1)
        even = {1 + i: Q(math.comb(n, i), denominator) for i in range(n + 1) if i % 2 == 0}
        odd = {1 + i: Q(math.comb(n, i), denominator) for i in range(n + 1) if i % 2 == 1}
        if sum(even.values(), Q(0)) != 1 or sum(odd.values(), Q(0)) != 1:
            failures.append({"kind": "moment-probability", "r": r})
        if max((*even.keys(), *odd.keys())) > kappa - 2:
            failures.append({"kind": "moment-valid-support", "r": r})

        def expectation(mu: dict[int, Q], fn) -> Q:
            return sum((mass * fn(d) for d, mass in mu.items()), Q(0))

        for degree in range(r + 1):
            for family, fn in (
                ("power", lambda d, degree=degree: d**degree),
                ("rising", lambda d, degree=degree: rising(d, degree)),
                ("falling", lambda d, degree=degree: falling(d, degree)),
            ):
                if expectation(even, fn) != expectation(odd, fn):
                    failures.append({"kind": "low-moment", "r": r, "degree": degree, "family": family})
        high_difference = expectation(even, lambda d: rising(d, n)) - expectation(odd, lambda d: rising(d, n))
        predicted = Q((-1) ** n * math.factorial(n), denominator)
        killed_difference = expectation(even, lambda d: attachment_transformed(kappa, d, n, 0)) - expectation(
            odd, lambda d: attachment_transformed(kappa, d, n, 0)
        )
        if high_difference != predicted or killed_difference != predicted / rising(kappa, n):
            failures.append({"kind": "high-moment", "r": r})
        moment_rows.append({"r": r, "kappa": kappa, "high_difference": record(high_difference), "killed_difference": record(killed_difference)})

    reset_samples = []
    for q, c, lam, a, theta, C in (
        (Q(3, 8), Q(3, 8), Q(1, 2), Q(1, 8), Q(1, 32), Q(9, 32)),
        (Q(7, 19), Q(11, 23), Q(5, 13), Q(1, 9), Q(-2, 31), Q(3, 4)),
    ):
        b = c * lam
        if not (0 <= a <= b):
            failures.append({"kind": "reset-sample-domain"})
        leftover = q * (b - a) * lam
        normalized_variables = q * (C - q * (a / q) * lam) + (theta / q) ** 2 / (c / q)
        expanded = q * (C - a * lam) + theta * theta / (q * c)
        if leftover < 0 or normalized_variables != expanded:
            failures.append({"kind": "one-power-algebra"})
        reset_samples.append({"leftover": record(leftover), "envelope": record(expanded)})

    payload = {
        "claim": "fresh immutable referee audit of M147",
        "scope": "auxiliary unweighted reset excursion only",
        "python": platform.python_version(),
        "seed": None,
        "immutable_hashes": observed_hashes,
        "counts": {
            "forest_rows": forest_rows,
            "attachment_entries": attachment_rows,
            "root_literal_entries": root_rows,
            "root_mean_cases": root_cases,
            "recurrence_cases": len(recurrence_cases),
            "L1_states": l1_rows,
            "moment_pairs": len(moment_rows),
        },
        "recurrence_cases": recurrence_cases,
        "exact_witness": {name: record(value) for name, value in observed_exact.items()},
        "paired_named_data": paired_named_data,
        "reachability": reachability,
        "moment_pairs": moment_rows,
        "moment_scope": {
            "measures_are_valid_on_fixed_kappa_deficits": True,
            "measures_are_claimed_as_single_parent_attachment_laws": False,
            "measures_are_claimed_reachable_under_the_DAG": False,
            "conclusion": "unrestricted fixed-moment compression cannot determine every attachment degree",
        },
        "reset_one_power_samples": reset_samples,
        "failure_count": len(failures),
        "failures": failures,
    }
    encoded = json.dumps(payload, indent=2, sort_keys=True) + "\n"
    args.output.write_text(encoded)
    print(json.dumps({"failure_count": len(failures), "output_sha256": hashlib.sha256(encoded.encode()).hexdigest(), "counts": payload["counts"]}, sort_keys=True))


if __name__ == "__main__":
    main()
