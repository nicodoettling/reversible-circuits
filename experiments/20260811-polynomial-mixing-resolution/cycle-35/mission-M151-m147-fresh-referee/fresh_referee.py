#!/usr/bin/env python3
"""Clean-room exact audit of frozen M147.

This checker imports no predecessor source or result.  It reconstructs root
compositions from cut masks and compares M147's transformed formulas with the
original `(K,R)` formulas using exact rational arithmetic.
"""

