#!/usr/bin/env python3
"""Clean-room exact/certified boundary checks for the M239 YCM theorem.

This program imports no predecessor module or data.  Every q, kernel, G, A,
B, coefficient, and prefix is recomputed from the closed definitions using
Fraction arithmetic.  The only transcendental in the auxiliary SG/GG1
checks is e; it is enclosed by a rational Taylor interval with a rigorous
geometric tail bound.  Square-root envelope checks are performed after
squaring nonnegative rational quantities.

Finite checks are falsification evidence, not the proof of the all-rank
statement.
"""

from __future__ import annotations

import argparse
import json
import math
from fractions import Fraction
from functools import lru_cache


@lru_cache(maxsize=None)
def c(n: int) -> Fraction:
    """The rational part of b_n: b_n = c_n/e^n."""
    assert n >= 1
    return Fraction(n ** (n - 1), math.factorial(n))


def e_interval(last_term: int = 45) -> tuple[Fraction, Fraction]:
    """Rigorous enclosure of e using terms 0,...,last_term.

    The first omitted term is 1/(last_term+1)!.  All later successive ratios
    are at most 1/(last_term+2), so a geometric tail bounds the remainder.
    """
    assert last_term >= 1
    lower = sum((Fraction(1, math.factorial(r)) for r in range(last_term + 1)), Fraction())
    first_omitted = Fraction(1, math.factorial(last_term + 1))
    tail = first_omitted * Fraction(last_term + 2, last_term + 1)
    return lower, lower + tail


E_LO, E_HI = e_interval()


def epow_interval(power: int) -> tuple[Fraction, Fraction]:
    if power >= 0:
        return E_LO**power, E_HI**power
    return Fraction(1, E_HI ** (-power)), Fraction(1, E_LO ** (-power))


def b_ratio_interval(a: int, n: int) -> tuple[Fraction, Fraction]:
    """Certified interval for b_a/b_n."""
    elo, ehi = epow_interval(n - a)
    rational = c(a) / c(n)
    return rational * elo, rational * ehi


def rational_over_b_interval(value: Fraction, n: int) -> tuple[Fraction, Fraction]:
    """Certified interval for a nonnegative rational value divided by b_n."""
    assert value >= 0
    return value * E_LO**n / c(n), value * E_HI**n / c(n)


def q(k: int, s: int) -> Fraction:
    return Fraction(k, k - 1) * c(s) * c(k - s) / c(k)


def h(R: int, r: int) -> Fraction:
    return Fraction((r - 1) * (r - 2), r * R)


def kernel(R: int, r: int, x: int) -> Fraction:
    assert 1 <= x < r
    return c(x) * c(r - x) / (R * c(r))


def g_sources(k: int, x: int) -> tuple[Fraction, Fraction, Fraction]:
    D, R, j, L = 2 * k - 1, 2 * k - 3, (k - 1) // 2, (3 * k - 1) // 2
    assert 1 <= x <= L - 1
    survivor = q(k, x) * h(R, D - x) if x <= j else Fraction()
    short = sum(
        (q(k, s) * (s - x - 1) * kernel(R, s, x) for s in range(x + 1, j + 1)),
        Fraction(),
    )
    long = Fraction()
    for s in range(1, j + 1):
        r = D - s
        assert x < r
        long += q(k, s) * (r - x - 1) * kernel(R, r, x)
    assert survivor >= 0 and short >= 0 and long >= 0
    return survivor, short, long


@lru_cache(maxsize=None)
def G(k: int, x: int) -> Fraction:
    return sum(g_sources(k, x), Fraction())


def B(k: int, y: int) -> Fraction:
    D, j, L = 2 * k - 1, (k - 1) // 2, (3 * k - 1) // 2
    assert 2 <= y <= L
    if y < k:
        return Fraction(D - 2 * y, D) * G(k, y) + Fraction(y - 1, D) * G(k, y - 1)
    if y == k:
        return Fraction(k - 1, D) * G(k, k - 1)
    z = y - k
    assert 1 <= z <= j
    return Fraction(k - z, D) * G(k, k + z - 1) + Fraction(z, D) * G(k, z)


def A(k: int, y: int) -> Fraction:
    R = 2 * k - 3
    if y >= k:
        return Fraction()
    assert 2 <= y < k
    m = k - y
    bracket = Fraction(m) + Fraction((m - 1) * (m - 2), k - 1)
    # Exponents cancel because y+m=k.
    return Fraction(2, R) * c(y) * c(m) / c(k) * bracket


def coeff(k: int, y: int) -> Fraction:
    return B(k, y) - A(k, y)


def interval_abs_from(center: Fraction, lo: Fraction, hi: Fraction) -> Fraction:
    assert lo <= hi
    return max(abs(lo - center), abs(hi - center))


def check_squared_leq(value: Fraction, radicand: int, constant: int) -> bool:
    """Check |value|*sqrt(radicand) <= constant exactly."""
    assert radicand >= 0 and constant >= 0
    return value * value * radicand <= constant * constant


def audit_k(k: int) -> dict[str, object]:
    assert k >= 3 and k % 2 == 1
    D, R, j, L = 2 * k - 1, 2 * k - 3, (k - 1) // 2, (3 * k - 1) // 2

    assert sum((q(k, s) for s in range(1, j + 1)), Fraction()) == 1

    # All G calls generated by every seam formula must remain on M229's
    # corrected domain 1,...,L-1.
    called: set[int] = set()
    for y in range(2, L + 1):
        if y < k:
            called.update((y, y - 1))
        elif y == k:
            called.add(k - 1)
        else:
            z = y - k
            called.update((k + z - 1, z))
    assert called and min(called) >= 1 and max(called) <= L - 1

    max_survivor = 0.0
    max_short = 0.0
    max_long = 0.0
    max_gg1 = 0.0
    for x in range(1, j + 1):
        survivor, short, long = g_sources(k, x)
        ratios = [rational_over_b_interval(v, x)[1] for v in (survivor, short, long)]
        assert ratios[0] < 23
        assert ratios[1] < 14
        assert ratios[2] < 135
        total_hi = rational_over_b_interval(survivor + short + long, x)[1]
        assert total_hi < 172
        max_survivor = max(max_survivor, float(ratios[0]))
        max_short = max(max_short, float(ratios[1]))
        max_long = max(max_long, float(ratios[2]))
        max_gg1 = max(max_gg1, float(total_hi))

        # Independently certify the four ratio constants used in the analytic
        # GG1 proof (their universal derivation is reviewed in proof_audit.md).
        assert b_ratio_interval(k - x, k)[1] < 9
        M = D - x
        assert b_ratio_interval(M, k)[1] < 3
        for s in range(1, j + 1):
            assert b_ratio_interval(k - s, D - s)[1] < 18

    max_sg = 0.0
    max_small_B = 0.0
    max_small_A = 0.0
    for x in range(1, k // 4 + 1):
        ratio_lo, ratio_hi = rational_over_b_interval(G(k, x), x)
        sg = Fraction(128 * (x + 1), k)
        assert ratio_lo >= 2 - sg and ratio_hi <= 2 + sg
        max_sg = max(max_sg, float(max(abs(ratio_lo - 2), abs(ratio_hi - 2)) * k / (x + 1)))

    for y in range(2, k // 4 + 1):
        m = k - y
        # Exact P and a certified Q interval verify the safe, sign-agnostic
        # Q|P-1|+|Q-1| triangle: |A-2b_y| <= 72 y b_y/k.
        P = (Fraction(m) + Fraction((m - 1) * (m - 2), k - 1)) / R
        Q_lo, Q_hi = b_ratio_interval(m, k)
        assert 0 <= P <= 1
        assert 1 - P <= Fraction(4 * y, k)
        assert Q_lo >= 1 and Q_hi - 1 <= Fraction(16 * y, k)
        assert Q_hi <= 5
        safe_triangle = Q_hi * (1 - P) + (Q_hi - 1)
        assert safe_triangle <= Fraction(36 * y, k)

        ar_lo, ar_hi = rational_over_b_interval(A(k, y) / 2, y)
        assert interval_abs_from(Fraction(1), ar_lo, ar_hi) <= Fraction(36 * y, k)
        max_small_A = max(
            max_small_A,
            float(2 * interval_abs_from(Fraction(1), ar_lo, ar_hi) * k / y),
        )

        br_lo, br_hi = rational_over_b_interval(B(k, y), y)
        bound = Fraction(234 * (y + 1), k)
        assert interval_abs_from(Fraction(2), br_lo, br_hi) <= bound
        max_small_B = max(
            max_small_B,
            float(interval_abs_from(Fraction(2), br_lo, br_hi) * k / (y + 1)),
        )

    max_gg2 = 0.0
    for x in range(j, L):
        value = G(k, x) * k
        assert check_squared_leq(value, D - x, 70)
        max_gg2 = max(max_gg2, float(G(k, x) * k * math.sqrt(D - x)))

    # The region partition is exhaustive and disjoint.  Every comparison
    # below is exact after squaring.
    regions: dict[str, int] = {"E1": 0, "E2": 0, "E3": 0, "E4": 0}
    prefix = Fraction()
    max_envelope_fraction = 0.0
    max_ycm_scaled = 0.0
    boundary_rows: list[dict[str, object]] = []
    for y in range(2, L + 1):
        value = coeff(k, y)
        if y <= j:
            region, radicand, constant = "E1", y, 3000
            assert check_squared_leq(value * k, radicand, constant)
            scaled = abs(float(value)) * k * math.sqrt(y) / constant
        elif y < k:
            m = k - y
            region, radicand, constant = "E2", m, 176
            assert check_squared_leq(value * k, radicand, constant)
            scaled = abs(float(value)) * k * math.sqrt(m) / constant
        elif y == k:
            region, radicand, constant = "E3", k**3, 70
            assert check_squared_leq(value, radicand, constant)
            scaled = abs(float(value)) * k ** 1.5 / constant
        else:
            z = y - k
            region, radicand, constant = "E4", z, 242
            assert check_squared_leq(value * k, radicand, constant)
            scaled = abs(float(value)) * k * math.sqrt(z) / constant
        regions[region] += 1
        max_envelope_fraction = max(max_envelope_fraction, scaled)

        prefix += value
        assert prefix * prefix * k * k <= 6906 * 6906 * y
        assert prefix * prefix * k * k <= 7000 * 7000 * y
        ycm_scaled = abs(float(prefix)) * k / math.sqrt(y)
        max_ycm_scaled = max(max_ycm_scaled, ycm_scaled)
        if k in (3, 5, 7):
            boundary_rows.append(
                {
                    "y": y,
                    "region": region,
                    "coefficient": f"{value.numerator}/{value.denominator}",
                    "prefix": f"{prefix.numerator}/{prefix.denominator}",
                    "scaled_prefix": ycm_scaled,
                }
            )

    assert sum(regions.values()) == L - 1
    expected = {
        "E1": max(j - 1, 0),
        "E2": j,
        "E3": 1,
        "E4": j,
    }
    assert regions == expected

    return {
        "k": k,
        "D": D,
        "R": R,
        "j": j,
        "L": L,
        "G_called_min": min(called),
        "G_called_max": max(called),
        "region_counts": regions,
        "max_certified_GG1_source_ratios": {
            "survivor": max_survivor,
            "short": max_short,
            "long": max_long,
            "total": max_gg1,
        },
        "max_certified_SG_constant": max_sg,
        "max_GG2_constant": max_gg2,
        "max_certified_small_B_constant": max_small_B,
        "max_certified_small_A_constant": max_small_A,
        "max_envelope_fraction": max_envelope_fraction,
        "max_YCM_scaled_prefix": max_ycm_scaled,
        "boundary_rows": boundary_rows,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-k", type=int, default=51)
    args = parser.parse_args()
    assert args.max_k >= 3
    rows = [audit_k(k) for k in range(3, args.max_k + 1, 2)]
