#!/usr/bin/env python3
"""Exact audit of long-cycle conjugation on parking multiplicity macros.

For every minimal factorization generated by Stanley's parking-function
bijection, conjugate every transposition by c=(0 1 ... n-1), i.e. add one
to each endpoint modulo n.  Group by the source lower-endpoint multiplicity
vector and test whether the target vector (or its degree histogram) is a
deterministic function of the source.  A smallest mismatch rigorously
refutes plain macro cyclic/Vervaat lumping; finite deterministic behavior
would not prove a universal formula.
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
from collections import defaultdict
from pathlib import Path


HERE = Path(__file__).resolve().parent
M35 = HERE.parents[1] / "cycle-08" / "mission-M35-general-parking-flow"
sys.path.insert(0, str(M35))

import adjacent_bypass_probe as base  # noqa: E402
import leaf_rotation_probe as leaf  # noqa: E402


def conjugate_edge(edge: tuple[int, int], n: int) -> tuple[int, int]:
    endpoints = sorted(((edge[0] + 1) % n, (edge[1] + 1) % n))
    return endpoints[0], endpoints[1]


def degrees_of_edges(edges: tuple[tuple[int, int], ...], r: int) -> tuple[int, ...]:
    lower = tuple(sorted(edge[0] for edge in edges))
    return leaf.counts_from_macro(lower)


def run(n: int) -> dict:
    r = n - 1
    by_source: dict[tuple[int, ...], dict[tuple[int, ...], list[dict]]] = defaultdict(
        lambda: defaultdict(list)
    )
    total = 0
    for labels in itertools.product(range(r), repeat=r):
        if not base.is_parking_word(labels):
            continue
        edges = base.factor_word(base.inverse_chain(labels))
        source = degrees_of_edges(edges, r)
        conjugated = tuple(conjugate_edge(edge, n) for edge in edges)
        target = degrees_of_edges(conjugated, r)
        by_source[source][target].append(
            {
                "parking_labels": labels,
                "factor_edges": edges,
                "conjugated_edges": conjugated,
            }
        )
        total += 1

    macro_mismatches = []
    histogram_mismatches = []
    exchangeability_mismatches = []
    for source, targets in sorted(by_source.items()):
        if len(targets) > 1:
            target_rows = []
            for target, witnesses in sorted(targets.items()):
                target_rows.append(
                    {
                        "target": target,
                        "count": len(witnesses),
                        "witness": witnesses[0],
                    }
                )
            macro_mismatches.append({"source": source, "targets": target_rows})
        histograms: dict[tuple[int, ...], tuple[int, ...]] = {}
        for target in targets:
            histograms.setdefault(tuple(sorted(target)), target)
        if len(histograms) > 1:
            histogram_mismatches.append(
                {
                    "source": source,
                    "target_histograms": [
                        {"histogram": histogram, "example_target": target}
                        for histogram, target in sorted(histograms.items())
                    ],
                }
            )
        by_histogram: dict[tuple[int, ...], list[tuple[tuple[int, ...], int]]] = (
            defaultdict(list)
        )
        for target, witnesses in targets.items():
            by_histogram[tuple(sorted(target))].append((target, len(witnesses)))
        for histogram, rows in sorted(by_histogram.items()):
            if len(rows) >= 2 and len({count for _, count in rows}) > 1:
                exchangeability_mismatches.append(
                    {
                        "source": source,
                        "target_histogram": histogram,
                        "target_counts": [
                            {"target": target, "count": count}
                            for target, count in sorted(rows)
                        ],
                    }
                )
                break

    return {
        "n": n,
        "r": r,
        "factorizations": total,
        "source_macros": len(by_source),
        "nondeterministic_source_macros": len(macro_mismatches),
        "histogram_nondeterministic_source_macros": len(histogram_mismatches),
        "histogram_orbit_nonexchangeable_source_macros": len(
            exchangeability_mismatches
        ),
        "first_macro_mismatch": macro_mismatches[0] if macro_mismatches else None,
        "first_histogram_mismatch": (
            histogram_mismatches[0] if histogram_mismatches else None
        ),
        "first_histogram_orbit_count_mismatch": (
            exchangeability_mismatches[0] if exchangeability_mismatches else None
        ),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n-min", type=int, default=3)
    parser.add_argument("--n-max", type=int, default=7)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = {
        "convention": "(pq)(x)=p(q(x)); tuple products left-to-right; conjugation t -> c t c^-1",
        "claim_tested": "long-cycle conjugation is deterministic on the parking degree vector, or at least its degree histogram",
        "scope": "finite exact falsifier; a mismatch refutes lumpability, finite agreement proves no universal formula",
        "rows": [run(n) for n in range(args.n_min, args.n_max + 1)],
    }
    args.output.write_text(json.dumps(output, indent=2, default=list) + "\n")


if __name__ == "__main__":
    main()
